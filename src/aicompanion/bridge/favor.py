"""外人使唤她办事时，像真人那样回（负责人 2026-11-10 13:51）。

"除了主人以外要是问她'去帮我查下这是什么梗'，按真人的形式进行回复。"
真人被群友、网友使唤时不会说"好的，我来帮你查"，也不会贴一份查询结果：
帮不帮看关系和心情；愿意帮也是随口说个大概（"好像是…""我搜了下说是…"），不愿意就一句"自己搜"。

这里只做一件确定性的小事：认出"这是在让她办事 / 问某个梗"（线索，不下结论），判断仍交给同一个大脑。
要不要替他查，由她自己决定（T20：回复里写 <mind lookup="词"/>，见 community/lookup.py）。
"""
from __future__ import annotations
import re

FAVOR = re.compile(r'帮(?:我|忙|个忙|咱|俺|一下)|替我|麻烦你|'
                   r'给我(?:查|搜|找|写|算|翻译|总结|看看|讲|解释|推荐|整|画|做)|'
                   r'(?:去|来)?(?:查|搜|百度|谷歌)(?:一下|下|查|搜)|能不能(?:帮|查|搜|写|算|翻译)')
MEME_ASK = re.compile(r'(?:什么|啥|哪来的)\s*(?:梗|意思|来头|典故)|(?:梗|词)的?出处|啥来头')
QUOTED = re.compile(r'[“"「『《]([^”"」』》]{2,16})[”"」』》]')
NAMED = re.compile(r'([\w一-鿿·\-]{1,24}?)\s*(?:到底)?(?:是|算)?(?:个)?(?:什么|啥)\s*(?:梗|意思|来头|典故)')
LEAD = re.compile(r'^(?:(?:去|来)?(?:帮我|帮忙|帮咱|给我|替我|麻烦你?))?(?:(?:去|来)?(?:查|搜|看|问|讲|解释)+(?:一下|下)?)?')
FILLER = re.compile(r'^(?:你|知道|晓得|懂|这个|那个|这句|那句|这|那|的|吗)+')

RULE = ('\n【他在让你帮忙办事】你不是他的助手，也不是搜索引擎。像真人被群友、网友使唤时那样，帮不帮、帮到什么程度，看你们的关系和你现在的心情：'
        '关系不错、心情也行，就顺手帮，口气随意，用自己的话说个大概，拿不准就说"好像是""我记得是"；'
        '一般或者不熟，可以只说自己知道的，也可以吐槽一句让他自己搜；没好感就不帮，或者不理。'
        '自己不知道又没查到，就说不知道、没听过，别编。'
        '怎么说都行，就是别用助手腔：不说"好的""我来帮你查""以下是""根据搜索结果"，不列点、不贴链接、不写成一份说明。')
WHICH = '\n他没说清楚问的是哪个梗、哪句话：能从上面的聊天里看出来就直接接，看不出来就像真人那样问一句"哪个"。'


def wants_favor(text: str) -> bool:
    text = str(text or '')
    return bool(FAVOR.search(text) or MEME_ASK.search(text))


def asked_term(text: str) -> str:
    """他问的是哪个词：引号里的优先，其次是"X 是什么梗"前面的 X；"这 / 这个"这类指代不算。"""
    text = str(text or '')
    if not MEME_ASK.search(text): return ''
    quoted = QUOTED.search(text)
    if quoted: return quoted[1].strip()
    named = NAMED.search(text)
    if not named: return ''
    term = FILLER.sub('', LEAD.sub('', named[1]))
    return term if 2 <= len(term) <= 12 else ''
